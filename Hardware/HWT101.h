/**
  ******************************************************************************
  * @file    HWT101.h
  * @brief   HWT101(维特智能 单轴陀螺仪) 串口驱动 —— 偏航角 Yaw + Z轴角速度 ωz
  * @note    通信: USART3, PD8=USART3_TX -> 陀螺仪 RX, PD9=USART3_RX <- 陀螺仪 TX (交叉接线)
  *          参数: 115200, 8 数据位, 无校验, 1 停止位, 供电 5V
  *          协议: 维特智能标准 11 字节帧, 帧头 0x55
  *                0x55 0x53 ...  -> 角度帧(第 7/8 字节为 Yaw)
  *                0x55 0x52 ...  -> 角速度帧(第 5/6 字节 ωy, 第 7/8 字节 ωz)
  *                第 11 字节 = 前 10 字节累加和的低 8 位
  *          模块上电即主动连续发送, 接收全程在 USART3 中断里用状态机完成, 不阻塞主循环。
  *
  *          【上电自动清零】见 HWT101_ZERO_MODE 宏。默认 = 软件偏置法:
  *          上电后等模块启动完成(约1s), 把那一刻的朝向记下来作为零点, 之后输出的
  *          yaw 都是相对该朝向的角度 —— 起步时 Yaw 必定为 0, 走直矫正的目标角才正确。
  ******************************************************************************
  */
#ifndef __HWT101_H
#define __HWT101_H

#include "stm32f4xx.h"

/* ===================== 接口定义(换串口/换引脚只改 HWT101.c 顶部) =====================
 * USART3 在 F407 上有两组可选引脚(PB10/PB11 或 PD8/PD9), 是"或"的关系, 同一时刻只能用一组。
 * 本工程用 PD8/PD9, 所以 PB10/PB11 是空闲的普通 GPIO —— OLED 用这两个脚没有冲突。
 * ================================================================================ */

/* 帧解析结果, 单位已经换算好 */
typedef struct
{
	float    yaw;       /* 偏航角(已减去上电零点), 单位 度, 范围 -180.0 ~ +180.0 */
	float    gyro_z;    /* Z 轴角速度, 单位 度/秒, 范围 -2000.0 ~ +2000.0 */
	uint32_t cnt;       /* 已成功解析并校验通过的总帧数, 用于判断"数据是否在刷新" */
	uint8_t  valid;     /* 0=从未收到过有效帧, 1=已收到过有效帧(之后恒为 1) */
} HWT101_Data_t;

void     HWT101_Init(void); /* 初始化 USART3 + PD8/PD9 + 接收中断 */
void     HWT101_ReadAndPrint(void); /* Poll and print over USART1 */
void     HWT101_ConfigPoll(void);             /* 放主循环里: 非阻塞地推进上电配置流程 */
uint8_t  HWT101_ConfigBusy(void);             /* 1=上电配置(清零/设速率)还没跑完 */
uint8_t  HWT101_Snapshot(HWT101_Data_t *out); /* 取一份最新数据快照(内部关中断保证原子性) */

void     HWT101_ZeroHere(void);               /* 把"当前朝向"设为 0 度(走直矫正前可随时重设) */
void     HWT101_ClearZero(void);              /* 取消软件零点, 恢复模块的绝对朝向 */

/* 便捷接口: 只关心某个量时用, 都是原子读, 可随时在主循环里调用 */
float    HWT101_GetYaw(void);                 /* 偏航角(已减零点), 单位 度 */
float    HWT101_GetGyroZ(void);               /* Z 轴角速度, 单位 度/秒 */
uint32_t HWT101_GetCount(void);               /* 累计有效帧数 */
uint8_t  HWT101_IsOnline(void);               /* 1=收到过有效帧, 0=一直没有 */

extern volatile HWT101_Data_t g_hwt101;       /* 中断里写入, 一般请用上面的接口读取 */

#endif
